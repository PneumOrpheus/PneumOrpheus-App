export type Translations = (typeof translations)[AppLanguage];

export const normalizeLanguage = (value?: string | null): AppLanguage => {
  if (value === "no" || value === "nb" || value === "nn") {
    return "no";
  }

  return "en";
};

export const getTranslations = (language: AppLanguage): Translations => {
  return translations[language];
};
